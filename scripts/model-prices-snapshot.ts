/**
 * prices:snapshot — write the prices a deployment meters at before it has
 * read the lists itself (src/llm/price-snapshot.ts).
 *
 *   npm run prices:snapshot
 *
 * A running deployment reads both price lists every few hours and keeps
 * what they say in its database (services/model-price-service.ts), so a
 * price change reaches it without a release. The snapshot is the floor
 * under that: what a fresh database, a deployment that cannot reach the
 * lists, the corpus scripts and the unit suite meter at. It is made by the
 * same rules as the live catalog (src/llm/price-sources.ts), starting from
 * the snapshot already here: a price in it changes only when both lists
 * state the new one, a new model is priced from either, and nothing is
 * dropped. What changed, what is new and what was held is printed.
 *
 * Run it now and then; nothing goes wrong between runs but a fresh install
 * metering at older prices until its first refresh. Never edit the
 * snapshot by hand. A deployment that wants a price of its own states it
 * in MODEL_PRICES.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fetchPriceListings } from "../src/llm/price-fetch.js";
import { PRICE_SNAPSHOT } from "../src/llm/price-snapshot.js";
import { describePrice, reconcile, type Catalog } from "../src/llm/price-sources.js";

const here = dirname(fileURLToPath(import.meta.url));
const SNAPSHOT_PATH = join(here, "..", "src", "llm", "price-snapshot.ts");

/** The snapshot module's source: one model to a line, so a change is a line. */
export function renderSnapshot(catalog: Catalog): string {
  const lines = Object.entries(catalog)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, price]) => `  ${JSON.stringify(id)}: ${JSON.stringify(price)},`);
  return [
    "/**",
    " * The prices a deployment meters at until it has read the price lists",
    " * itself. GENERATED by `npm run prices:snapshot` (scripts/model-prices-snapshot.ts)",
    " * from OpenRouter's model list and LiteLLM's price file, by the rules in",
    " * price-sources.ts. Do not edit by hand: a deployment that wants a price",
    " * of its own states it in MODEL_PRICES.",
    " *",
    " * USD per million tokens. `sources` names the lists that stated each price",
    " * when it was taken.",
    " */",
    'import type { Catalog } from "./price-sources.js";',
    "",
    "export const PRICE_SNAPSHOT: Catalog = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const { listings, failures } = await fetchPriceListings();
  for (const f of failures) console.error(`  could not read ${f.source}: ${f.error}`);
  if (listings.length === 0) {
    console.error("Neither list could be read; the snapshot is unchanged.");
    process.exit(1);
  }
  const { catalog, changes, held } = reconcile(PRICE_SNAPSHOT, listings);
  writeFileSync(SNAPSHOT_PATH, renderSnapshot(catalog));

  console.log(`\n${Object.keys(catalog).length} models priced in src/llm/price-snapshot.ts`);
  const added = changes.filter((c) => c.from === null);
  const moved = changes.filter((c) => c.from !== null);
  if (added.length) console.log(`\nNew (${added.length}):`);
  for (const c of added) console.log(`  ${c.model.padEnd(36)} ${describePrice(c.to)}  [${c.sources.join(", ")}]`);
  if (moved.length) console.log(`\nChanged (${moved.length}):`);
  for (const c of moved) {
    console.log(`  ${c.model.padEnd(36)} ${describePrice(c.from!)}\n  ${"".padEnd(36)} → ${describePrice(c.to)}`);
  }
  if (held.length) console.log(`\nHeld (${held.length}):`);
  for (const h of held) console.log(`  ${h.model.padEnd(36)} ${h.reason}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
